#!/usr/bin/env bash
# KPS v2 WSDL'lerinden veri sözleşmelerini (src/KpsV2.Client/Contracts/KpsContracts.g.cs) yeniden üretir.
# KPS bir alan/metot eklediğinde çalıştırın, ardından `git diff` ile değişikliği inceleyip testleri koşun.
#
#   tools/generate-contracts.sh            # test ortamı WSDL'i (IP kısıtı yok)
#   KPS_WSDL_HOST=https://kpsv2.saglik.gov.tr tools/generate-contracts.sh   # Prod (tanımlı IP'den)
set -euo pipefail

KOK="$(cd "$(dirname "$0")/.." && pwd)"
HEDEF="$KOK/src/KpsV2.Client/Contracts/KpsContracts.g.cs"
HOST="${KPS_WSDL_HOST:-https://kpsv2test.saglik.gov.tr}"
GECICI="$(mktemp -d)"
trap 'rm -rf "$GECICI"' EXIT

echo "WSDL indiriliyor: $HOST"
curl -fsS -m 60 -o "$GECICI/kps.wsdl"   "$HOST/?wsdl&service=kpsServices&isTest=True"
curl -fsS -m 60 -o "$GECICI/param.wsdl" "$HOST/?wsdl&service=parametreServices&isTest=True"

echo "dotnet-svcutil kuruluyor (geçici)"
dotnet tool install --tool-path "$GECICI/tools" dotnet-svcutil --version 8.0.0 >/dev/null

echo "Sözleşmeler üretiliyor"
# Not: svcutil, KPS'in WS2007FederationHttpBinding'i .NET Core'da desteklenmediği için uç noktaları atlar
# ("uyumsuz bağlama" uyarıları beklenir). Yalnızca veri sözleşmelerini kullanıyoruz.
"$GECICI/tools/dotnet-svcutil" "$GECICI/kps.wsdl" "$GECICI/param.wsdl" \
  --namespace "*,KpsV2.Contracts" --outputDir "$GECICI/out" --outputFile KpsContracts.cs \
  --serializer DataContractSerializer --sync --noLogo --targetFramework net8.0 > "$GECICI/svcutil.log" 2>&1 || true
# svcutil bu uyarılar yüzünden sıfırdan farklı kodla çıkar; asıl ölçüt dosyanın üretilmiş olmasıdır.

URETILEN="$GECICI/out/KpsContracts.cs"
[ -s "$URETILEN" ] || { cat "$GECICI/svcutil.log" >&2; echo "svcutil çıktı üretmedi" >&2; exit 1; }
BAS=$(grep -n '^namespace KpsV2.Contracts' "$URETILEN" | cut -d: -f1)
SON=$(grep -n 'ConfigurationName="KpsV2.Contracts.IKpsServices"' "$URETILEN" | cut -d: -f1)
[ -n "$BAS" ] && [ -n "$SON" ] || { echo "Beklenmeyen svcutil çıktısı" >&2; exit 1; }

{
  cat <<'EOF'
// <auto-generated>
//   KPS v2 WSDL veri sözleşmeleri. Elle DEĞİŞTİRMEYİN; yeniden üretmek için: tools/generate-contracts.sh
//   Kaynak: https://kpsv2test.saglik.gov.tr/?wsdl&service=kpsServices + parametreServices
//   Üretici: dotnet-svcutil --serializer DataContractSerializer (WCF istemci kısmı çıkarılmıştır).
//   Bu tiplere ek davranışlar KpsContracts.Ekler.cs içinde partial sınıflarla eklenir.
// </auto-generated>
#nullable disable
#pragma warning disable CS1591
EOF
  # WCF servis sözleşmesi/istemci kısmı (ServiceContract'tan itibaren) atılır; yalnızca veri tipleri kalır.
  sed -n "${BAS},$((SON - 2))p" "$URETILEN"
  echo '}'
} > "$HEDEF"

echo "Yazıldı: $HEDEF"
echo "Sonra: dotnet build && dotnet test"
