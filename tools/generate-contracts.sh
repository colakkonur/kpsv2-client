#!/usr/bin/env bash
# KPS WSDL'lerinden veri sözleşmelerini yeniden üretir:
#   src/KpsV2.Client/Contracts/KpsContracts.g.cs  — Sağlık Bakanlığı KPS v2
#   src/KpsV2.Client/Contracts/NviContracts.g.cs  — NVİ KPS (kpsbasvuru.nvi.gov.tr'deki herkese açık WSDL'ler)
# KPS bir alan/metot eklediğinde çalıştırın, ardından `git diff` ile değişikliği inceleyip testleri koşun.
#
#   tools/generate-contracts.sh            # test ortamı WSDL'i (IP kısıtı yok)
#   KPS_WSDL_HOST=https://kpsv2.saglik.gov.tr tools/generate-contracts.sh   # Prod (tanımlı IP'den)
set -euo pipefail

KOK="$(cd "$(dirname "$0")/.." && pwd)"
HEDEF="$KOK/src/KpsV2.Client/Contracts/KpsContracts.g.cs"
HOST="${KPS_WSDL_HOST:-https://kpsv2test.saglik.gov.tr}"
GECICI="$(mktemp -d)"
trap 'rm -rf "$GECICI"' EXIT

echo "WSDL indiriliyor: $HOST"
curl -fsS -m 60 -o "$GECICI/kps.wsdl"   "$HOST/?wsdl&service=kpsServices&isTest=True"
curl -fsS -m 60 -o "$GECICI/param.wsdl" "$HOST/?wsdl&service=parametreServices&isTest=True"

echo "dotnet-svcutil kuruluyor (geçici)"
dotnet tool install --tool-path "$GECICI/tools" dotnet-svcutil --version 8.0.0 >/dev/null

echo "Sözleşmeler üretiliyor"
# Not: svcutil, KPS'in WS2007FederationHttpBinding'i .NET Core'da desteklenmediği için uç noktaları atlar
# ("uyumsuz bağlama" uyarıları beklenir). Yalnızca veri sözleşmelerini kullanıyoruz.
"$GECICI/tools/dotnet-svcutil" "$GECICI/kps.wsdl" "$GECICI/param.wsdl" \
  --namespace "*,KpsV2.Contracts" --outputDir "$GECICI/out" --outputFile KpsContracts.cs \
  --serializer DataContractSerializer --sync --noLogo --targetFramework net8.0 > "$GECICI/svcutil.log" 2>&1 || true
# svcutil bu uyarılar yüzünden sıfırdan farklı kodla çıkar; asıl ölçüt dosyanın üretilmiş olmasıdır.

URETILEN="$GECICI/out/KpsContracts.cs"
[ -s "$URETILEN" ] || { cat "$GECICI/svcutil.log" >&2; echo "svcutil çıktı üretmedi" >&2; exit 1; }
BAS=$(grep -n '^namespace KpsV2.Contracts' "$URETILEN" | cut -d: -f1)
SON=$(grep -n 'ConfigurationName="KpsV2.Contracts.IKpsServices"' "$URETILEN" | cut -d: -f1)
[ -n "$BAS" ] && [ -n "$SON" ] || { echo "Beklenmeyen svcutil çıktısı" >&2; exit 1; }

{
  cat <<'EOF'
// <auto-generated>
//   KPS v2 WSDL veri sözleşmeleri. Elle DEĞİŞTİRMEYİN; yeniden üretmek için: tools/generate-contracts.sh
//   Kaynak: https://kpsv2test.saglik.gov.tr/?wsdl&service=kpsServices + parametreServices
//   Üretici: dotnet-svcutil --serializer DataContractSerializer (WCF istemci kısmı çıkarılmıştır).
//   Bu tiplere ek davranışlar KpsContracts.Ekler.cs içinde partial sınıflarla eklenir.
// </auto-generated>
#nullable disable
#pragma warning disable CS1591
EOF
  # WCF servis sözleşmesi/istemci kısmı (ServiceContract'tan itibaren) atılır; yalnızca veri tipleri kalır.
  sed -n "${BAS},$((SON - 2))p" "$URETILEN"
  echo '}'
} > "$HEDEF"

echo "Yazıldı: $HEDEF"

# ---------------------------------------------------------------------------------------------
# NVİ KPS (kpsv2.nvi.gov.tr): her servisin kendi WSDL'i var; NVİ bunları herkese açık yayınlar.
# Yeni bir NVİ servisi için adını NVI_SERVISLER'e ekleyin (ad, NVİ'nin onay yazısındaki servis adıdır).
# ---------------------------------------------------------------------------------------------
NVI_HEDEF="$KOK/src/KpsV2.Client/Contracts/NviContracts.g.cs"
NVI_WSDL="https://kpsbasvuru.nvi.gov.tr/Services/Wsdl.ashx?Service="
NVI_SERVISLER="TCKimlikNoDogrulaServis KisiSorgulaTCKimlikNoServis"

NVI_CIKTILAR=()
for servis in $NVI_SERVISLER; do
  echo "NVİ WSDL indiriliyor: $servis"
  curl -fsS -m 60 -o "$GECICI/$servis.wsdl" "$NVI_WSDL$servis"
  grep -q '<error>' "$GECICI/$servis.wsdl" && { cat "$GECICI/$servis.wsdl" >&2; echo; echo "NVİ bu servis adını tanımıyor: $servis" >&2; exit 1; }
  # Servisler aynı XML namespace'ini paylaşır; svcutil birden çok WSDL verilince yalnızca ilkinin tiplerini alır.
  # Bu yüzden her servis ayrı üretilir, ortak tipler (Parametre, TarihBilgisi...) aşağıda bir kez yazılır.
  "$GECICI/tools/dotnet-svcutil" "$GECICI/$servis.wsdl" \
    --namespace "*,KpsV2.Nvi.Contracts" --outputDir "$GECICI/nvi-$servis" --outputFile Nvi.cs \
    --serializer DataContractSerializer --sync --noLogo --targetFramework net8.0 > "$GECICI/nvi-$servis.log" 2>&1 || true
  [ -s "$GECICI/nvi-$servis/Nvi.cs" ] || { cat "$GECICI/nvi-$servis.log" >&2; echo "svcutil çıktı üretmedi: $servis" >&2; exit 1; }
  NVI_CIKTILAR+=("$GECICI/nvi-$servis/Nvi.cs")
done

{
  cat <<EOF
// <auto-generated>
//   NVİ KPS WSDL veri sözleşmeleri. Elle DEĞİŞTİRMEYİN; yeniden üretmek için: tools/generate-contracts.sh
//   Kaynak: ${NVI_WSDL}<servis> — $NVI_SERVISLER
//   Üretici: dotnet-svcutil --serializer DataContractSerializer (WCF istemci kısmı çıkarılmıştır).
//   Bu tiplere ek davranışlar NviContracts.Ekler.cs içinde partial sınıflarla eklenir.
// </auto-generated>
#nullable disable
#pragma warning disable CS1591
namespace KpsV2.Nvi.Contracts
{
    using System.Runtime.Serialization;
EOF
  # svcutil tipleri "    " satırıyla ayırır. Her dosyada ServiceContract'a kadarki tip blokları alınır,
  # aynı adlı tip (servislerin ortak tipleri) yalnızca bir kez yazılır.
  awk '
    function yaz() {
      if (blok != "" && match(blok, /(class|enum) [A-Za-z0-9_]+/)) {
        ad = substr(blok, RSTART, RLENGTH); sub(/^(class|enum) /, "", ad)
        if (!(ad in yazildi)) { yazildi[ad] = 1; printf "    \n%s", blok }
      }
      blok = ""
    }
    FNR == 1 { icerde = 0; bitti = 0; blok = "" }
    bitti { next }
    /^namespace / { icerde = 1; next }
    !icerde { next }
    /ServiceContractAttribute/ { blok = ""; bitti = 1; next }
    $0 == "    " { yaz(); next }
    /^    \[/ && blok == "" { blok = $0 "\n"; next }
    blok != "" { blok = blok $0 "\n" }
  ' "${NVI_CIKTILAR[@]}"
  echo '}'
} > "$NVI_HEDEF"

echo "Yazıldı: $NVI_HEDEF"
echo "Sonra: dotnet build && dotnet test"
